#!/usr/bin/env python3
"""Generate include/generated_sheets.h from the logic sheets. Refuses to run if preflight has errors."""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from preflight import check, load  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent.parent / "include" / "generated_sheets.h"


def f(x):
    return f"{float(x)}f"


def main():
    errs, _ = check("logic")
    if errs:
        print("Preflight not clean, not generating:")
        for e in errs:
            print("  ", e)
        sys.exit(1)

    world = load("world")["rows"][0]
    board = load("board")["rows"][0]
    inputs = load("inputs")["rows"]
    tricks = load("tricks")["rows"]
    sc = load("scoring")["rows"][0]

    L = ["// GENERATED by tools/gen.py from sheets/*.json. Do not edit by hand.", "#pragma once", "", "namespace snow {", ""]
    L.append("enum class InputId { " + ", ".join(r["id"] for r in inputs) + " };")
    L.append("enum class TrickKind { Spin, Grab };")
    L.append("")
    L.append("struct WorldRow { float units_per_meter; float gravity_ms2; };")
    L.append(f"constexpr WorldRow WORLD = {{{f(world['units_per_meter'])}, {f(world['gravity_ms2'])}}};")
    L.append("")
    L.append("struct BoardRow { const char* id; float gravity_scale, friction_snow, friction_other, brake_drag, min_slope_deg, max_speed, steer_rate_deg_s, carve_grip, turn_speed_ref, jump_impulse, air_control, air_spin_rate_deg_s; };")
    L.append(
        "constexpr BoardRow BOARD = {\"%s\", %s};" % (
            board["id"],
            ", ".join(f(board[k]) for k in ["gravity_scale", "friction_snow", "friction_other", "brake_drag", "min_slope_deg", "max_speed", "steer_rate_deg_s", "carve_grip", "turn_speed_ref", "jump_impulse", "air_control", "air_spin_rate_deg_s"]),
        )
    )
    L.append("")
    surfaces = load("surfaces")["rows"]
    L.append("enum class SurfaceId { " + ", ".join(r["id"] for r in surfaces) + " };")
    L.append("struct SurfaceRow { const char* id; float friction_mult, steer_mult; };")
    L.append("constexpr SurfaceRow SURFACES[] = {")
    for s in surfaces:
        L.append(f"    {{\"{s['id']}\", {f(s['friction_mult'])}, {f(s['steer_mult'])}}},")
    L.append("};")
    L.append(f"constexpr int SURFACE_COUNT = {len(surfaces)};")
    L.append("")
    L.append("struct TrickRow { const char* id; const char* name; TrickKind kind; InputId input; float rotation_deg; float min_air_time_s; int points; };")
    L.append("constexpr TrickRow TRICKS[] = {")
    for t in tricks:
        kind = "TrickKind::Spin" if t["kind"] == "spin" else "TrickKind::Grab"
        L.append(f"    {{\"{t['id']}\", \"{t['name']}\", {kind}, InputId::{t['input']}, {f(t['rotation_deg'])}, {f(t['min_air_time_s'])}, {int(t['points'])}}},")
    L.append("};")
    L.append(f"constexpr int TRICK_COUNT = {len(tricks)};")
    L.append("")
    L.append("struct ScoringRow { float combo_step; int combo_max; int wipeout_penalty; float wipeout_speed_keep, min_air_time_for_score_s, landing_tolerance_deg; };")
    L.append(f"constexpr ScoringRow SCORING = {{{f(sc['combo_step'])}, {int(sc['combo_max'])}, {int(sc['wipeout_penalty'])}, {f(sc['wipeout_speed_keep'])}, {f(sc['min_air_time_for_score_s'])}, {f(sc['landing_tolerance_deg'])}}};")
    L += ["", "}  // namespace snow", ""]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
